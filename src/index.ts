import { Hono } from 'hono';
import { serveStatic } from 'hono/bun';
import { execSync } from 'child_process';
import api from './routes/api';
import { startYtdlpAutoUpdate } from './services/ytdlp-updater';
import { startCacheCleanup } from './services/cache';
import { maintenance } from './middleware/maintenance';

const app = new Hono();

/**
 * Check if required dependencies are installed
 */
function checkDependencies() {
  const ytdlpPath = process.env.YTDLP_PATH || 'yt-dlp';
  const dependencies = ['ffmpeg', ytdlpPath];
  
  console.log('🔍 Checking dependencies...');
  
  for (const dep of dependencies) {
    try {
      // Use --version or similar to check if binary exists and is executable
      const cmd = dep.includes('yt-dlp') ? `${dep} --version` : `${dep} -version`;
      execSync(cmd, { stdio: 'ignore' });
      console.log(`✅ ${dep} is available`);
    } catch (e) {
      console.error(`❌ Error: Required dependency '${dep}' not found.`);
      console.error(`Please ensure it is installed and in your PATH, or check your .env configuration.`);
      process.exit(1);
    }
  }
}

// Check dependencies before starting
checkDependencies();

// Keep yt-dlp current. YouTube breaks older releases every few weeks, which
// shows up as most downloads failing with 403s until the binary is updated.
startYtdlpAutoUpdate();

// Expired YouTube lookups were never deleted; purge them daily.
startCacheCleanup();

// Must run first: when MAINTENANCE_MODE=true it answers most requests itself.
app.use('/*', maintenance());

// Cache headers for static assets.
//
// This used to send `no-store` for JS/CSS, which re-downloaded ~110KB of app.js
// and styles.css on every single page view and hurt LCP on repeat visits. The
// filenames aren't content-hashed, so we can't cache them forever either: a
// short TTL plus stale-while-revalidate keeps repeat views cheap while a deploy
// still reaches everyone within a few minutes.
app.use('/*', async (c, next) => {
  const path = c.req.path;
  await next();

  if (path.endsWith('.js') || path.endsWith('.css')) {
    c.header('Cache-Control', 'public, max-age=300, stale-while-revalidate=86400');
  } else if (/\.(png|jpg|jpeg|webp|svg|ico|woff2?|mp3)$/.test(path)) {
    // Media and icons change rarely, and are replaced by name when they do.
    c.header('Cache-Control', 'public, max-age=604800');
  } else if (path.endsWith('.html') || path === '/' || path.startsWith('/random-dance')) {
    // Landing pages are rebuilt from analytics, so let crawlers revalidate.
    c.header('Cache-Control', 'public, max-age=0, must-revalidate');
  }
});

app.use('/*', serveStatic({ root: './public' }));

// The new builder was tried out at /studio.html before it became the home page,
// and the old builder stayed at /classic.html for a while after.
app.get('/studio.html', (c) => c.redirect('/', 301));
app.get('/classic.html', (c) => c.redirect('/', 301));

// Serve package.json for version info
app.get('/package.json', serveStatic({ path: './package.json' }));

// Mount API routes
app.route('/api', api);

// Fallback to index.html for SPA-like behavior
app.get('/', serveStatic({ path: './public/index.html' }));

// Landing pages live at /random-dance/<group> without the .html extension.
// They're generated by scripts/build-landing-pages.ts from analytics data.
app.get('/random-dance', (c) => c.redirect('/random-dance/', 301));
app.get('/random-dance/', serveStatic({ path: './public/random-dance/index.html' }));
app.get('/random-dance/:slug', async (c, next) => {
  const slug = c.req.param('slug');
  // Only ever resolve a plain slug to a file, never a traversal.
  if (!/^[a-z0-9-]+$/.test(slug)) return next();
  const file = Bun.file(`./public/random-dance/${slug}.html`);
  if (!(await file.exists())) return next();
  return c.html(await file.text());
});

// Serve admin page
app.get('/admin', serveStatic({ path: './public/admin.html' }));

const port = process.env.PORT || 3000;
// Only Caddy (on this machine) should reach the app; it adds HTTPS in front.
// Listening on every interface let anyone skip it via http://<server-ip>:3000.
const hostname = process.env.HOST || '127.0.0.1';

console.log(`🎵 K-Pop Random Dance Generator running on http://${hostname}:${port}`);

export default {
  port,
  hostname,
  fetch: app.fetch,
  idleTimeout: 60, // Increase timeout to 60s for long YouTube searches
};
